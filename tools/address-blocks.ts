/**
 * Writes src/lib/modes/address-blocks.ts: which State each block of 24-bit aircraft
 * addresses belongs to, from ICAO Annex 10 Volume III, Part I, Chapter 9, Table 9-1
 * ("Allocation of aircraft addresses to States"), as text (see tools/README.md):
 *
 *   pdftotext -layout annex10-vol3.pdf annex10-vol3.txt
 *   bun tools/address-blocks.ts annex10-vol3.txt > src/lib/modes/address-blocks.ts
 *
 * Each row of the table is a State and a 24-bit pattern, MSB first, in groups of
 * 4 2 3 3 2 10 bits: 0 and 1 are fixed, a dash is either. The fixed bits are the block's
 * prefix. A long State name wraps onto the next line ("Democratic People's" /
 * "Republic of Korea"); everything else between rows is page furniture.
 */
const path = process.argv[2];
if (!path) throw new Error('usage: bun tools/address-blocks.ts annex10-vol3.txt');
const lines = (await Bun.file(path).text()).split('\n');

const start = lines.findIndex((l) => l.includes('Table 9-1. Allocation of aircraft addresses'));
const amendment = lines
	.slice(start)
	.find((l) => /^\s*No\. \d+/.test(l))
	?.trim()
	.split(/\s+/)[1];
const ROW =
	/^ (\S.*?)\s{2,}.*?([01–]{4})\s+([01–]{2})\s+([01–]{3})\s+([01–]{3})\s+([01–]{2})\s+([01–]{10})\s*$/;
/** Lines that look like a wrapped name but aren't. */
const FURNITURE = /^(State\s{2}|Part I|Other allocations|Note|Number|Allocation|Annex|No\.)/;

const rows: { state: string; prefix: string }[] = [];
let previousWasRow = false;
for (const line of lines.slice(start)) {
	const row = ROW.exec(line);
	if (row) {
		const bits = row.slice(2).join('');
		const prefix = bits.slice(0, bits.indexOf('–') === -1 ? 24 : bits.indexOf('–'));
		if (bits.slice(prefix.length).replaceAll('–', '') !== '') throw new Error(`gap: ${line}`);
		// Strip the leading '*' column marks that pdftotext may glue to the name.
		rows.push({ state: row[1].replace(/\s+\*.*$/, '').trim(), prefix });
		previousWasRow = true;
		continue;
	}
	const text = line.trim();
	if (previousWasRow && /^ {1,3}[A-Za-z(]/.test(line) && !FURNITURE.test(text) && !/\d/.test(text))
		rows[rows.length - 1].state += ` ${text}`;
	previousWasRow = false;
	if (text.startsWith('CHAPTER 10')) break;
}

// The two ICAO rows carry a footnote number: 1 temporary addresses, 2 special use.
const NAMES: Record<string, string> = {
	ICAO1: 'ICAO (temporary addresses)',
	ICAO2: 'ICAO (special use for flight safety)'
};
for (const r of rows) r.state = NAMES[r.state] ?? r.state;

// Blocks must not overlap: one prefix may not start another.
const sorted = rows.toSorted((a, b) => (a.prefix < b.prefix ? -1 : 1));
for (const a of sorted)
	for (const b of sorted)
		if (a !== b && b.prefix.startsWith(a.prefix))
			throw new Error(`${a.state} (${a.prefix}) contains ${b.state} (${b.prefix})`);

const hex = (n: number) => n.toString(16).toUpperCase().padStart(6, '0');
const entries = sorted.map(({ state, prefix }) => {
	const from = parseInt(prefix.padEnd(24, '0'), 2);
	const to = parseInt(prefix.padEnd(24, '1'), 2);
	if (state.includes("'")) throw new Error(`quote in ${state}`);
	return `\t['${hex(from)}', '${hex(to)}', '${state}']`;
});

console.log(`/**
 * Which State each block of 24-bit aircraft addresses belongs to: ICAO Annex 10, Volume III,
 * Part I, Chapter 9, Table 9-1 (Amendment ${amendment ?? '?'}). ${rows.length} blocks, sorted, none overlapping.
 * Generated by tools/address-blocks.ts; don't edit.
 *
 * Each entry: first address, last address (hex), State. Addresses outside every block are
 * unallocated (or a corrupted message).
 */
export const ADDRESS_BLOCKS: readonly (readonly [from: string, to: string, state: string])[] = [
${entries.join(',\n')}
];`);

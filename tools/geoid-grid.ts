/**
 * Writes src/lib/weather/egm96.ts: the EGM96 geoid on a 2° grid, from GeographicLib's
 * 15-minute grid (egm96-15.pgm, see tools/README.md). Prints how far bilinear
 * interpolation on the 2° grid strays from the full grid, which egm96.ts quotes.
 *
 *   bun tools/geoid-grid.ts path/to/egm96-15.pgm > src/lib/weather/egm96.ts
 *
 * The PGM format (GeographicLib's Geoid class docs): a text header with "# Offset" and
 * "# Scale" comments, then 1440 × 721 big-endian 16-bit values, one per 15' from 90°N
 * down to 90°S and from 0°E eastwards. Height in metres = Offset + Scale × value.
 */
const STEP = 2; // degrees
const PER_DEGREE = 4; // the source grid's points per degree (15')

const path = process.argv[2];
if (!path) throw new Error('usage: bun tools/geoid-grid.ts egm96-15.pgm');
const bytes = new Uint8Array(await Bun.file(path).arrayBuffer());

// Header: "P5", comments, "width height", "maxval": 3 lines that aren't comments.
let at = 0;
const header: string[] = [];
while (header.filter((l) => !l.startsWith('#')).length < 3) {
	const end = bytes.indexOf(10, at);
	header.push(new TextDecoder().decode(bytes.subarray(at, end)));
	at = end + 1;
}
const comment = (key: string) =>
	Number(header.find((l) => l.startsWith(`# ${key} `))!.split(' ')[2]);
const offset = comment('Offset');
const scale = comment('Scale');
const [width, height] = header
	.filter((l) => !l.startsWith('#'))[1]
	.split(' ')
	.map(Number);
const view = new DataView(bytes.buffer, at);
const full = (row: number, col: number) =>
	offset + scale * view.getUint16(2 * (row * width + (((col % width) + width) % width)));

const rows = 180 / STEP + 1;
const cols = 360 / STEP;
const grid = Array.from({ length: rows }, (_, r) =>
	Array.from({ length: cols }, (_, c) =>
		Math.round(full(r * STEP * PER_DEGREE, c * STEP * PER_DEGREE))
	)
);

// The same interpolation as geoid.ts, against every point of the full grid.
const s = STEP * PER_DEGREE;
let max = 0;
let squares = 0;
let europe = 0;
for (let i = 0; i < height; i++) {
	for (let j = 0; j < width; j++) {
		const r = Math.min(Math.floor(i / s), rows - 2);
		const c = Math.floor(j / s);
		const a = i / s - r;
		const b = j / s - c;
		const at = (rr: number, cc: number) => grid[rr][cc % cols];
		const v =
			(1 - a) * ((1 - b) * at(r, c) + b * at(r, c + 1)) +
			a * ((1 - b) * at(r + 1, c) + b * at(r + 1, c + 1));
		const error = Math.abs(v - full(i, j));
		max = Math.max(max, error);
		squares += error * error;
		const lat = 90 - i / PER_DEGREE;
		const lon = j / PER_DEGREE;
		if (lat >= 35 && lat <= 72 && (lon >= 345 || lon <= 40)) europe = Math.max(europe, error);
	}
}
console.error(
	`2° grid vs 15': max ${max.toFixed(1)} m, rms ${Math.sqrt(squares / (width * height)).toFixed(1)} m, Europe max ${europe.toFixed(1)} m`
);
console.error(`spot values (15' grid): 52N 14E ${full(38 * 4, 14 * 4).toFixed(2)} m`);

console.log(`/**
 * The EGM96 geoid: how far mean sea level lies above (+) or below (−) the WGS84 ellipsoid,
 * in whole metres, every ${STEP}° from 90°N to 90°S (rows) and from 0°E eastwards (columns).
 * Generated by tools/geoid-grid.ts from GeographicLib's 15-minute grid; don't edit.
 *
 * EGM96 is the US National Geospatial-Intelligence Agency's Earth Gravitational Model
 * (a work of the US government, public domain); GeographicLib (MIT) publishes it as grids.
 * Bilinear interpolation on this ${STEP}° grid (geoid.ts) stays within ${max.toFixed(0)} m of the full
 * grid everywhere (rms ${Math.sqrt(squares / (width * height)).toFixed(1)} m), within ${europe.toFixed(0)} m over Europe.
 */
export const EGM96_STEP = ${STEP};

export const EGM96 = \`
${grid.map((row) => row.join(' ')).join('\n')}
\`;`);
